import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import rateLimit from 'express-rate-limit';
import { env } from './config/env';
import { requireAuth, csrfGuard, errorHandler } from './middleware/auth';
import auth from './routes/auth'; import notes from './routes/notes'; import cats from './routes/categories';
import dates from './routes/dates'; import reminders from './routes/reminders'; import calendar from './routes/calendar';
export const app = express();
app.use(helmet()); app.use(cors({ origin: env.FRONTEND_URL, credentials: true })); app.use(express.json({ limit: '1mb' })); app.use(cookieParser());
app.use('/api', rateLimit({ windowMs: 15 * 60_000, limit: 600 }), csrfGuard);
app.use('/api/auth', auth);
app.use('/api/notes', requireAuth, notes); app.use('/api/categories', requireAuth, cats); app.use('/api/dates', requireAuth, dates);
app.use('/api/reminders', requireAuth, reminders); app.use('/api/calendar', requireAuth, calendar);
app.use(errorHandler);
